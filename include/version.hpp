#ifndef _VERSION_HPP_
#define _VERSION_HPP_

#define CHECKPOINT_VERSION_MAJOR 1
#define CHECKPOINT_VERSION_MINOR 1

#define CHECKPOINT_STRINGIFY_VALUE(value) #value
#define CHECKPOINT_STRINGIFY(value) CHECKPOINT_STRINGIFY_VALUE(value)

#define CHECKPOINT_VERSION_STRING \
    CHECKPOINT_STRINGIFY(CHECKPOINT_VERSION_MAJOR) "." \
    CHECKPOINT_STRINGIFY(CHECKPOINT_VERSION_MINOR)

#define CHECKPOINT_VERSION_MESSAGE \
    "checkpoint version " CHECKPOINT_VERSION_STRING "\n" \
    "Source: https://github.com/KaiManabe/checkpoint"

#endif
